'use strict';

/**
 * Pipeline: the I/O orchestration that ties ingest → merge → write → index.
 *
 * This is what the installer and CLI call. All heavy logic lives in the pure
 * modules; here we only read/write files and keep a report.
 */

const fs = require('fs');
const path = require('path');
const { discoverSkills, discoverSource, dedupeIds } = require('./discover');
const { ingest, bestCategory, toEntry } = require('./ingest');
const { mergeIntoCategory, removeSegment } = require('./merge');
const { buildIndex } = require('./indexer');
const { readSegment } = require('./segment');
const { collectAssets, rewriteAssetRefs, copyAssets, removeAssets, listAssets, attachAssets } = require('./assets');
const { TOC_OPEN, TOC_CLOSE, SEGMENTS_OPEN, SEGMENTS_CLOSE, overlapScore, containmentScore } = require('./lib');

const INDEX_DIR = '.anabol';
const INDEX_FILE = 'index.json';

/** Category template used when the structure is empty (first install). */
function categorySkeleton(id, description) {
  return [
    '---',
    `name: ${id}`,
    `description: ${description || id}`,
    '---',
    '',
    `# ${id}`,
    '',
    'Category skill maintained by Anabol for Agents. Sub-skills are merged into this file',
    'as addressable segments; do not split them into separate files.',
    '',
    '## Segments',
    '',
    TOC_OPEN,
    '<!-- Generated by Anabol: one line per merged sub-skill with its line range. -->',
    TOC_CLOSE,
    '',
    '---',
    '',
    SEGMENTS_OPEN,
    SEGMENTS_CLOSE,
    '',
  ].join('\n');
}

/**
 * Rewrite the TOC block inside a category skill from the computed index.
 * @param {string} content
 * @param {Array<{id:string,description:string,startLine:number,endLine:number}>} segs
 * @returns {string}
 */
function renderToc(content, segs) {
  const text = String(content);
  const openIdx = text.indexOf(TOC_OPEN);
  const closeIdx = text.indexOf(TOC_CLOSE);
  if (openIdx === -1 || closeIdx === -1 || closeIdx < openIdx) return text;

  const body = segs.length
    ? segs.map((s) => `- ${s.id}${s.description ? ` — ${s.description}` : ''} (lines ${s.startLine}–${s.endLine})`).join('\n')
    : '<!-- no segments yet -->';

  return `${text.slice(0, openIdx + TOC_OPEN.length)}\n${body}\n${text.slice(closeIdx)}`;
}

/**
 * Install a source package into a structure by merging (never adding skills).
 *
 * @param {{sourceDir:string, structureRoot:string, dryRun?:boolean, force?:boolean}} opts
 * @returns {object} report
 */
function install(opts) {
  const { sourceDir, structureRoot, dryRun = false } = opts;
  const existing = discoverSkills(structureRoot);
  const source = dedupeIds(discoverSource(sourceDir));

  const existingEntries = existing.map((e) => toEntry(e));

  // Decide target category for every incoming skill.
  const plan = [];
  const skipped = [];
  if (existingEntries.length === 0) {
    // First install: no base to merge into — create one category per incoming skill.
    for (const inc of source) {
      plan.push({ incoming: inc, category: inc.id, create: true });
    }
  } else {
    const { assignments } = ingest(existingEntries, source, { threshold: 0.06 });
    for (const a of assignments) {
      let category = a.category || bestCategory(toEntry(a.source), existingEntries) || existingEntries[0].id;

      // A source skill whose id is already a category is that capability: do not
      // merge it into an unrelated category (that would move it) or into itself
      // (that would duplicate the category body). Skip and report it.
      if (category === a.source.id) {
        skipped.push({ id: a.source.id, reason: 'already installed as a category' });
        continue;
      }
      plan.push({ incoming: a.source, category, create: false });
    }
  }

  // Collect shipped assets and rewrite their relative references before the
  // body is merged, so the links point at the copy inside the category.
  for (const p of plan) {
    const skillDir = path.dirname(p.incoming.file);
    p.assets = collectAssets(skillDir);
    if (p.assets.length > 0) {
      p.incoming = {
        ...p.incoming,
        body: rewriteAssetRefs(p.incoming.body, p.incoming.id, p.assets),
      };
    }
  }

  // Load current contents (or skeletons for newly created categories).
  const contents = {};
  for (const e of existing) contents[e.id] = fs.readFileSync(e.file, 'utf8');
  for (const p of plan) {
    if (!(p.category in contents)) {
      contents[p.category] = categorySkeleton(p.category, p.incoming.description);
    }
  }

  // Merge each incoming body into its category. Remove any previous copy of the
  // same segment first so re-installing a package is idempotent. Track which
  // categories actually changed so untouched skills are never rewritten.
  const merged = [];
  const touched = new Set();
  for (const p of plan) {
    for (const category of Object.keys(contents)) {
      const next = removeSegment(contents[category], p.incoming.id);
      if (next !== contents[category]) touched.add(category);
      contents[category] = next;
    }
    contents[p.category] = mergeIntoCategory(contents[p.category], [
      { id: p.incoming.id, body: p.incoming.body, description: p.incoming.description },
    ]);
    touched.add(p.category);
    merged.push({
      id: p.incoming.id,
      category: p.category,
      created: p.create,
      assets: p.assets.length,
    });
  }

  // Index + TOC are mutually dependent: the TOC shows line ranges, and writing
  // the TOC shifts those lines. Do it in two passes so the stored lines are the
  // real ones (no fallback needed on the first read). Only touched categories
  // are re-rendered, so untouched files keep matching their index entries.
  const buildFor = () =>
    buildIndex(contents, {
      structureRoot,
      fileFor: (c) => path.posix.join(c, 'SKILL.md'),
    });

  let index = buildFor();
  for (const category of touched) {
    contents[category] = renderToc(contents[category], index.segments.filter((s) => s.category === category));
  }
  index = buildFor();
  for (const category of touched) {
    contents[category] = renderToc(contents[category], index.segments.filter((s) => s.category === category));
  }
  index = buildFor();

  // Write (unless dry run).
  if (!dryRun) {
    for (const category of touched) {
      const dir = path.join(structureRoot, category);
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'SKILL.md'), contents[category], 'utf8');
    }

    // Assets: drop any previous copy of these segments in every category, then
    // copy the current files next to the category they were merged into.
    for (const p of plan) {
      for (const category of Object.keys(contents)) {
        removeAssets(structureRoot, category, p.incoming.id);
      }
      if (p.assets.length > 0) {
        copyAssets(structureRoot, p.category, p.incoming.id, path.dirname(p.incoming.file), p.assets);
      }
    }

    attachAssets(index, (segment) => listAssets(structureRoot, segment.category, segment.id));
    writeIndexIfChanged(structureRoot, index);
  }

  return {
    ok: true,
    dryRun,
    structureRoot,
    sourceDir,
    skillsBefore: existing.length,
    skillsAfter: Object.keys(contents).length,
    countUnchanged: existing.length === 0 || Object.keys(contents).length === existing.length,
    merged,
    skipped,
    index: index.segments,
  };
}

/**
 * Write the index only when its content changed. When the segments are
 * identical, the previous `generatedAt` is kept, so a no-op install or reindex
 * is byte-identical (no churn in git or file watchers).
 *
 * @param {string} structureRoot
 * @param {object} index
 */
function writeIndexIfChanged(structureRoot, index) {
  const idxDir = path.join(structureRoot, INDEX_DIR);
  const idxPath = path.join(idxDir, INDEX_FILE);
  let previous = null;
  if (fs.existsSync(idxPath)) {
    try {
      previous = JSON.parse(fs.readFileSync(idxPath, 'utf8'));
    } catch {
      previous = null;
    }
  }

  if (
    previous &&
    previous.version === index.version &&
    JSON.stringify(previous.segments) === JSON.stringify(index.segments)
  ) {
    index.generatedAt = previous.generatedAt;
  }

  const serialized = JSON.stringify(index, null, 2) + '\n';
  if (previous && fs.readFileSync(idxPath, 'utf8') === serialized) return index;

  fs.mkdirSync(idxDir, { recursive: true });
  fs.writeFileSync(idxPath, serialized, 'utf8');
  return index;
}

/**
 * Rebuild the index for an existing structure (no merging).
 * @param {{structureRoot:string, write?:boolean}} opts
 */
function reindex(opts) {
  const { structureRoot, write = true } = opts;
  const skills = discoverSkills(structureRoot);
  const contents = {};
  for (const s of skills) contents[s.id] = fs.readFileSync(s.file, 'utf8');
  const index = buildIndex(contents, {
    structureRoot,
    fileFor: (c) => path.posix.join(c, 'SKILL.md'),
  });
  attachAssets(index, (segment) => listAssets(structureRoot, segment.category, segment.id));
  if (write) writeIndexIfChanged(structureRoot, index);
  return index;
}

/**
 * Read one segment by id from the index.
 * @param {{structureRoot:string, id:string}} opts
 */
function readById(opts) {
  const { structureRoot, id } = opts;
  const idxPath = path.join(structureRoot, INDEX_DIR, INDEX_FILE);
  const index = JSON.parse(fs.readFileSync(idxPath, 'utf8'));
  const seg = index.segments.find((s) => s.id === id);
  if (!seg) throw new Error(`unknown segment: ${id}`);
  const content = fs.readFileSync(path.join(structureRoot, seg.file), 'utf8');
  return { ...readSegment(content, seg), segment: seg };
}

/**
 * Find the best segment(s) for a task query without putting the index in the
 * caller's context. The CLI prints only the winning entry, so the orchestrator
 * pays a few hundred bytes instead of the whole index.
 *
 * @param {{structureRoot:string, query:string, limit?:number}} opts
 * @returns {Array<object>} matching segments with a `score`
 */
function findSegments(opts) {
  const { structureRoot, query, limit = 1 } = opts;
  if (!query || !String(query).trim()) throw new Error('find requires a query');

  const idxPath = path.join(structureRoot, INDEX_DIR, INDEX_FILE);
  const index = JSON.parse(fs.readFileSync(idxPath, 'utf8'));
  const scored = index.segments.map((seg) => {
    const text = `${seg.id} ${seg.description || ''} ${(seg.keywords || []).join(' ')}`;
    const score = Math.max(overlapScore(query, text), containmentScore(query, text));
    return { ...seg, score: Number(score.toFixed(4)) };
  });

  scored.sort((a, b) => b.score - a.score || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return scored.slice(0, Math.max(1, Number(limit) || 1));
}

module.exports = { install, reindex, readById, findSegments, renderToc, categorySkeleton, INDEX_DIR, INDEX_FILE };
